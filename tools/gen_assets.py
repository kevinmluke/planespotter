#!/usr/bin/env python3
"""Generates firmware assets from data/*.csv:

  src/generated/aircraft_db.{h,cpp}  families, type designators, airlines
  src/generated/silhouettes.cpp      1-bit side views, two sizes per family
  src/generated/worldmap.cpp         1-bit equirectangular land mask (Natural Earth)
  src/generated/cities.cpp           offline town list for the setup page (GeoNames)
  docs/silhouettes.png               contact sheet for review

Usage: python3 tools/gen_assets.py   (needs Pillow)
"""
import csv
import json
import os
import sys
import urllib.request

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(__file__))
from silhouettes import BUILDERS  # noqa: E402
import gen_cities  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "src", "generated")
CACHE = os.path.join(ROOT, "tools", "cache")

SIL_SMALL = (232, 80)
SIL_LARGE = (416, 140)
MAP_SIZE = (544, 272)
SUPERSAMPLE = 4
LAND_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson"

HEADER = "// GENERATED by tools/gen_assets.py from data/*.csv - do not edit by hand.\n"


def read_csv(name):
    with open(os.path.join(ROOT, "data", name), newline="", encoding="utf-8") as f:
        return [row for row in csv.reader(f) if row and not row[0].startswith("#")]


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# ----------------------------------------------------------------------------
# Silhouettes


def render_silhouette(sil, size):
    W, H = size
    margin = 2
    xs = [p[0] for _, pts, _, _ in sil.ops for p in pts]
    ys = [p[1] for _, pts, _, _ in sil.ops for p in pts]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    scale = min((W - 2 * margin) / (x1 - x0), (H - 2 * margin) / (y1 - y0))
    ss = SUPERSAMPLE
    img = Image.new("L", (W * ss, H * ss), 255)
    d = ImageDraw.Draw(img)
    ox = (W - (x1 - x0) * scale) / 2
    oy = (H - (y1 - y0) * scale) / 2
    px_per_unit = scale  # output pixels per design unit

    def tr(p):
        return ((ox + (p[0] - x0) * scale) * ss, (oy + (y1 - p[1]) * scale) * ss)

    for kind, pts, fill, extra in sil.ops:
        tp = [tr(p) for p in pts]
        color = 0 if fill else 255
        if kind == "poly":
            sep = extra
            if sep:
                # White halo around the shape, about `sep` output pixels wide (at least 1 px).
                w = max(1.0, sep * min(1.6, px_per_unit * 0.8)) * ss
                d.polygon(tp, fill=255)
                d.line(tp + [tp[0]], fill=255, width=int(round(w * 2)), joint="curve")
            d.polygon(tp, fill=color)
        elif kind == "line":
            w = max(1.0, extra * px_per_unit) * ss
            d.line(tp, fill=color, width=int(round(w)), joint="curve")
    img = img.resize((W, H), Image.BOX)
    return img.point(lambda v: 0 if v < 140 else 255, mode="1")


def bitmap_bytes(img):
    """1 bit per pixel, MSB first, rows padded to bytes; 1 = black (Adafruit drawBitmap convention)."""
    W, H = img.size
    px = img.load()
    out = bytearray()
    for y in range(H):
        byte, bits = 0, 0
        for x in range(W):
            byte = (byte << 1) | (1 if px[x, y] == 0 else 0)
            bits += 1
            if bits == 8:
                out.append(byte)
                byte, bits = 0, 0
        if bits:
            out.append(byte << (8 - bits))
    return out


def bytes_to_c(data, indent="    ", per_line=24):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append(indent + ",".join("0x%02x" % b for b in data[i:i + per_line]) + ",")
    return "\n".join(lines)


# ----------------------------------------------------------------------------
# World map


def load_land():
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, "ne_110m_land.geojson")
    if not os.path.exists(path):
        print("downloading", LAND_URL)
        urllib.request.urlretrieve(LAND_URL, path)
    with open(path) as f:
        return json.load(f)


def render_worldmap(size):
    W, H = size
    ss = SUPERSAMPLE
    img = Image.new("L", (W * ss, H * ss), 255)
    d = ImageDraw.Draw(img)
    land = load_land()

    def proj(lon, lat):
        return ((lon + 180) / 360 * W * ss, (90 - lat) / 180 * H * ss)

    for feat in land["features"]:
        geom = feat["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            outer = poly[0]
            d.polygon([proj(lon, lat) for lon, lat in outer], fill=0)
            for hole in poly[1:]:
                d.polygon([proj(lon, lat) for lon, lat in hole], fill=255)
    img = img.resize((W, H), Image.BOX)
    return img.point(lambda v: 0 if v < 128 else 255, mode="1")


# ----------------------------------------------------------------------------


def main():
    os.makedirs(GEN, exist_ok=True)
    families = read_csv("families.csv")
    fam_index = {row[0]: i for i, row in enumerate(families)}
    missing = [row[0] for row in families if row[0] not in BUILDERS]
    if missing:
        sys.exit("no silhouette builder for: " + ", ".join(missing))

    types = []
    for row in read_csv("aircraft_types.csv"):
        code, fam, name = row[0].strip(), row[1].strip(), row[2].strip()
        if fam not in fam_index:
            sys.exit(f"type {code}: unknown family {fam}")
        rarity = int(row[3]) if len(row) > 3 and row[3].strip() else -1
        types.append((code, fam_index[fam], name, rarity))
    codes = [t[0] for t in types]
    dupes = {c for c in codes if codes.count(c) > 1}
    if dupes:
        sys.exit("duplicate type codes: " + ", ".join(sorted(dupes)))
    types.sort(key=lambda t: t[0])

    airlines = sorted(((r[0].strip(), r[1].strip()) for r in read_csv("airlines.csv")), key=lambda a: a[0])

    # ---- aircraft_db.h / .cpp
    with open(os.path.join(GEN, "aircraft_db.h"), "w") as f:
        f.write(HEADER + f"""#pragma once

#include <cstdint>

namespace db {{

constexpr int kFamilyCount = {len(families)};
constexpr int kSilSmallW = {SIL_SMALL[0]}, kSilSmallH = {SIL_SMALL[1]};
constexpr int kSilLargeW = {SIL_LARGE[0]}, kSilLargeH = {SIL_LARGE[1]};

struct Family {{
  const char* key;
  const char* name;
  bool military;
  uint8_t rarity;
}};

struct TypeInfo {{
  const char* code;
  uint8_t family;
  const char* name;
  int8_t rarity;  // -1: use the family rarity
}};

struct Airline {{
  const char* prefix;
  const char* name;
}};

extern const Family kFamilies[kFamilyCount];
extern const TypeInfo kTypes[];
extern const int kTypeCount;
extern const Airline kAirlines[];
extern const int kAirlineCount;

// Silhouette bitmaps (1 = black, MSB first, rows padded to whole bytes).
extern const uint8_t* const kSilSmall[kFamilyCount];
extern const uint8_t* const kSilLarge[kFamilyCount];

constexpr int kMapW = {MAP_SIZE[0]}, kMapH = {MAP_SIZE[1]};
extern const uint8_t kWorldLand[];  // 1 = land

// Lookups (binary search over the sorted tables).
const TypeInfo* findType(const char* code);
// Longest airline prefix matching the callsign, followed by a digit or the end.
const Airline* findAirline(const char* callsign);
// Family for an aircraft with no known type, from its ADS-B emitter category.
int familyForCategory(const char* category);
int familyIndex(const char* key);
int typeRarity(const TypeInfo* t);

}}  // namespace db
""")

    def fam_by_key(k):
        return fam_index[k]

    with open(os.path.join(GEN, "aircraft_db.cpp"), "w") as f:
        f.write(HEADER + '#include "aircraft_db.h"\n\n#include <cstring>\n\nnamespace db {\n\n')
        f.write("const Family kFamilies[kFamilyCount] = {\n")
        for key, name, mil, rar in families:
            f.write(f"    {{{c_str(key)}, {c_str(name)}, {'true' if mil.strip() == '1' else 'false'}, {int(rar)}}},\n")
        f.write("};\n\nconst TypeInfo kTypes[] = {\n")
        for code, fi, name, rar in types:
            f.write(f"    {{{c_str(code)}, {fi}, {c_str(name)}, {rar}}},\n")
        f.write(f"}};\nconst int kTypeCount = {len(types)};\n\nconst Airline kAirlines[] = {{\n")
        for code, name in airlines:
            f.write(f"    {{{c_str(code)}, {c_str(name)}}},\n")
        f.write(f"}};\nconst int kAirlineCount = {len(airlines)};\n\n")
        f.write(f"""const TypeInfo* findType(const char* code) {{
  if (!code || !*code) return nullptr;
  int lo = 0, hi = kTypeCount - 1;
  while (lo <= hi) {{
    const int mid = (lo + hi) / 2;
    const int c = std::strcmp(code, kTypes[mid].code);
    if (c == 0) return &kTypes[mid];
    if (c < 0) hi = mid - 1;
    else lo = mid + 1;
  }}
  return nullptr;
}}

const Airline* findAirline(const char* cs) {{
  if (!cs || !*cs) return nullptr;
  const Airline* best = nullptr;
  size_t bestLen = 0;
  for (int i = 0; i < kAirlineCount; i++) {{
    const size_t n = std::strlen(kAirlines[i].prefix);
    if (n > bestLen && std::strncmp(cs, kAirlines[i].prefix, n) == 0 &&
        (cs[n] == 0 || (cs[n] >= '0' && cs[n] <= '9'))) {{
      best = &kAirlines[i];
      bestLen = n;
    }}
  }}
  return best;
}}

int familyIndex(const char* key) {{
  for (int i = 0; i < kFamilyCount; i++)
    if (std::strcmp(kFamilies[i].key, key) == 0) return i;
  return 0;
}}

int familyForCategory(const char* c) {{
  if (!c || c[0] == 0) return {fam_by_key('generic_jet')};
  if (c[0] == 'A') {{
    switch (c[1]) {{
      case '1': return {fam_by_key('single_low')};
      case '2': return {fam_by_key('lightjet')};
      case '7': return {fam_by_key('helicopter')};
      case '6': return {fam_by_key('fighter')};
      default: return {fam_by_key('generic_jet')};
    }}
  }}
  if (c[0] == 'B') {{
    switch (c[1]) {{
      case '1': return {fam_by_key('glider')};
      case '2': return {fam_by_key('balloon')};
      case '6': return {fam_by_key('uav')};
      default: return {fam_by_key('single_high')};
    }}
  }}
  return {fam_by_key('generic_jet')};
}}

int typeRarity(const TypeInfo* t) {{
  if (!t) return 0;
  return t->rarity >= 0 ? t->rarity : kFamilies[t->family].rarity;
}}

}}  // namespace db
""")

    # ---- silhouettes
    small_imgs, large_imgs = [], []
    with open(os.path.join(GEN, "silhouettes.cpp"), "w") as f:
        f.write(HEADER + '#include "aircraft_db.h"\n\nnamespace db {\nnamespace {\n\n')
        for key, *_ in families:
            sil = BUILDERS[key]()
            small = render_silhouette(sil, SIL_SMALL)
            large = render_silhouette(sil, SIL_LARGE)
            small_imgs.append(small)
            large_imgs.append(large)
            f.write(f"// {key}\nconst uint8_t s_{key}[] = {{\n{bytes_to_c(bitmap_bytes(small))}\n}};\n")
            f.write(f"const uint8_t l_{key}[] = {{\n{bytes_to_c(bitmap_bytes(large))}\n}};\n\n")
        f.write("}  // namespace\n\n")
        f.write("const uint8_t* const kSilSmall[kFamilyCount] = {" + ", ".join(f"s_{r[0]}" for r in families) + "};\n")
        f.write("const uint8_t* const kSilLarge[kFamilyCount] = {" + ", ".join(f"l_{r[0]}" for r in families) + "};\n")
        f.write("\n}  // namespace db\n")

    # ---- contact sheet
    cols = 6
    cw, ch = SIL_SMALL[0] + 16, SIL_SMALL[1] + 26
    rows = (len(families) + cols - 1) // cols
    sheet = Image.new("1", (cols * cw, rows * ch), 1)
    sd = ImageDraw.Draw(sheet)
    for i, (key, name, *_rest) in enumerate(families):
        x, y = (i % cols) * cw + 8, (i // cols) * ch + 4
        sheet.paste(small_imgs[i], (x, y))
        sd.text((x, y + SIL_SMALL[1] + 4), f"{i} {key}", fill=0)
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    sheet.save(os.path.join(ROOT, "docs", "silhouettes.png"))
    big = Image.new("1", (SIL_LARGE[0] * 3 + 40, SIL_LARGE[1] * 4 + 50), 1)
    showcase = ["a380", "beluga", "b747", "concorde", "fighter", "helicopter", "a400m", "b52", "v22", "b787", "atr", "bizjet"]
    for i, key in enumerate(showcase):
        big.paste(large_imgs[fam_index[key]], ((i % 3) * (SIL_LARGE[0] + 10) + 10, (i // 3) * (SIL_LARGE[1] + 10) + 10))
    big.save(os.path.join(ROOT, "docs", "silhouettes_large.png"))

    # ---- world map
    world = render_worldmap(MAP_SIZE)
    world.save(os.path.join(ROOT, "docs", "worldmap.png"))
    with open(os.path.join(GEN, "worldmap.cpp"), "w") as f:
        f.write(HEADER + '#include "aircraft_db.h"\n\nnamespace db {\n\n')
        f.write("// Natural Earth 1:110m land, equirectangular, 1 = land.\n")
        f.write(f"const uint8_t kWorldLand[] = {{\n{bytes_to_c(bitmap_bytes(world))}\n}};\n")
        f.write("\n}  // namespace db\n")

    gen_cities.build()
    print(f"{len(families)} families, {len(types)} types, {len(airlines)} airlines -> {GEN}")


if __name__ == "__main__":
    main()
