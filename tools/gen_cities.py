#!/usr/bin/env python3
"""Builds the offline town list used by the setup page (no internet needed).

Source: GeoNames cities15000 (CC BY 4.0, https://www.geonames.org), every place
with more than 15,000 inhabitants, plus each city's time zone converted to a
POSIX TZ string (from the IANA tz database via the `tzdata` package).

Extra towns below that size can be listed in data/extra_towns.csv.

Output: src/generated/cities.cpp, a gzip'd text file served to the phone as-is:

  line 1:  TZ<TAB>posix0<TAB>posix1...
  then:    name<TAB>region<TAB>CC<TAB>lat<TAB>lon<TAB>tzIndex     (sorted by population)
"""
import gzip
import os
import urllib.request
import zipfile

import tzdata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "tools", "cache")
BASE = "https://download.geonames.org/export/dump/"


def fetch(name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        print("downloading", BASE + name)
        urllib.request.urlretrieve(BASE + name, path)
    return path


def posix_tz(zone):
    """The POSIX TZ rule is the footer of a TZif v2+ file: '\\n<rule>\\n'."""
    path = os.path.join(os.path.dirname(tzdata.__file__), "zoneinfo", *zone.split("/"))
    try:
        data = open(path, "rb").read()
    except FileNotFoundError:
        return None
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode()
    return footer or None


def build():
    zpath = fetch("cities15000.zip")
    txt = os.path.join(CACHE, "cities15000.txt")
    if not os.path.exists(txt):
        zipfile.ZipFile(zpath).extract("cities15000.txt", CACHE)
    admin1 = {}
    for line in open(fetch("admin1CodesASCII.txt"), encoding="utf-8"):
        code, name, *_ = line.rstrip("\n").split("\t")
        admin1[code] = name

    tzs, tz_index, rows = [], {}, []
    for line in open(txt, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        name, lat, lon, cc, a1, pop, zone = f[1], float(f[4]), float(f[5]), f[8], f[10], int(f[14] or 0), f[17]
        rule = posix_tz(zone) or "UTC0"
        if rule not in tz_index:
            tz_index[rule] = len(tzs)
            tzs.append(rule)
        region = admin1.get(f"{cc}.{a1}", "")
        rows.append((pop, f"{name}\t{region}\t{cc}\t{lat:.2f}\t{lon:.2f}\t{tz_index[rule]}"))
    # Hand-picked extra towns (data/extra_towns.csv), skipping any already listed
    known = {(r[1].split("\t")[0], r[1].split("\t")[1], r[1].split("\t")[2]) for r in rows}
    with open(os.path.join(ROOT, "data", "extra_towns.csv"), encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            name, region, cc, lat, lon, zone, pop = [x.strip() for x in line.split(",")]
            if (name, region, cc) in known:
                continue
            rule = posix_tz(zone)
            if not rule:
                raise SystemExit(f"extra_towns.csv: unknown time zone {zone} for {name}")
            if rule not in tz_index:
                tz_index[rule] = len(tzs)
                tzs.append(rule)
            rows.append((int(pop or 0), f"{name}\t{region}\t{cc}\t{float(lat):.2f}\t{float(lon):.2f}\t{tz_index[rule]}"))
    rows.sort(key=lambda r: -r[0])
    body = "TZ\t" + "\t".join(tzs) + "\n" + "\n".join(r[1] for r in rows) + "\n"
    blob = gzip.compress(body.encode("utf-8"), compresslevel=9, mtime=0)

    out = os.path.join(ROOT, "src", "generated", "cities.cpp")
    with open(out, "w") as f:
        f.write("// GENERATED by tools/gen_cities.py from GeoNames cities15000 (CC BY 4.0) - do not edit.\n")
        f.write("#include <cstddef>\n#include <cstdint>\n\nnamespace db {\n\n")
        f.write(f"// {len(rows)} places, {len(tzs)} time zone rules, gzip'd TSV\n")
        f.write("extern const uint8_t kCitiesGz[] = {\n")
        for i in range(0, len(blob), 24):
            f.write("    " + ",".join("0x%02x" % b for b in blob[i:i + 24]) + ",\n")
        f.write(f"}};\nextern const size_t kCitiesGzLen = {len(blob)};\n\n}}  // namespace db\n")
    print(f"cities: {len(rows)} places, {len(tzs)} TZ rules, {len(body) // 1024} KB -> {len(blob) // 1024} KB gzip")
    return body


if __name__ == "__main__":
    build()
