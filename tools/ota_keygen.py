#!/usr/bin/env python3
"""Creates the OTA signing key pair.

  keys/ota_private.pem      KEEP SECRET, back it up. Anyone with it can push firmware.
  include/ota_pubkey.h      public key compiled into the firmware

Refuses to overwrite an existing private key: devices in the field only accept
updates signed by the key they were built with.
"""
import os
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRIV = os.path.join(ROOT, "keys", "ota_private.pem")
PUB_H = os.path.join(ROOT, "include", "ota_pubkey.h")


def write_header(public_key):
    pem = public_key.public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo).decode()
    lines = " \\\n".join(f'    "{line}\\n"' for line in pem.strip().splitlines())
    with open(PUB_H, "w") as f:
        f.write("// GENERATED by tools/ota_keygen.py - public half of the OTA signing key.\n")
        f.write("#pragma once\n\n#define OTA_PUBKEY_PEM \\\n" + lines + "\n")
    print("wrote", os.path.relpath(PUB_H, ROOT))


def main():
    if os.path.exists(PRIV):
        with open(PRIV, "rb") as f:
            key = serialization.load_pem_private_key(f.read(), password=None)
        print("private key already exists, re-exporting the public header only")
        write_header(key.public_key())
        return
    os.makedirs(os.path.dirname(PRIV), exist_ok=True)
    key = ec.generate_private_key(ec.SECP256R1())
    with open(PRIV, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                  serialization.NoEncryption()))
    os.chmod(PRIV, 0o600)
    print("wrote", os.path.relpath(PRIV, ROOT), "(back this up somewhere safe)")
    write_header(key.public_key())


if __name__ == "__main__":
    sys.exit(main())
